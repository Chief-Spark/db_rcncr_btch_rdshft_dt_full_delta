#!/usr/bin/env python3
"""Reescribe SQL de Amazon Redshift a PostgreSQL 16, para el banco local.

NO es un traductor de proposito general. Cubre exactamente lo que estos tres
repos usan, y se queda corto a proposito.

PRINCIPIO: donde Postgres admita una funcion equivalente, se define un SHIM en
shims.sql (esquema `rs`, puesto en el search_path) y aqui NO se toca el texto.
Reescribir texto es la ultima opcion, porque cada regla es una fuente de
errores propia. Por eso GETDATE, FNV_HASH, LEN y TRUNC(timestamp) no aparecen
en este archivo: se resuelven por sobrecarga.

Y la base de datos local se llama `ds_dba_rncr_batch`, de modo que las 14
referencias `ds_dba_rncr_batch.edf_views.xpm` resuelven solas: Postgres acepta
el nombre de tres partes cuando la primera es la base actual. Una regla menos.

Queda solo lo que no admite shim porque difiere la SINTAXIS, no el nombre:

  T1  NONATOMIC                                  opcion de procedimiento
  T2  WITH NO SCHEMA BINDING       Postgres no tiene enlace tardio de vistas
  T3  colas de almacenamiento  DISTSTYLE / DISTKEY(...) / SORTKEY(...) / ENCODE
  T4  DISTKEY / SORTKEY a nivel de columna, sin parentesis
  T5  IDENTITY(s, p)         ->  GENERATED BY DEFAULT AS IDENTITY (START ...)
  T6  LISTAGG(e, s) WITHIN GROUP (ORDER BY k)  ->  string_agg(e, s ORDER BY k)
  T7  DATEADD / DATEDIFF     la unidad va como palabra desnuda, no como texto
  T8  REGEXP_REPLACE de 3 argumentos          ->  cuarto argumento 'g'

T8 es el unico que corrige un COMPORTAMIENTO y no una sintaxis, y por eso es el
mas peligroso de los ocho: Redshift reemplaza TODAS las ocurrencias por
omision, Postgres solo la PRIMERA. Sin T8, los 17 sitios dan resultados
distintos en silencio -- entre ellos el REGEXP_REPLACE(valor, '[^0-9]', '') que
construye el diccionario de complementos de la Regla 2. Y no puede ser shim,
porque pg_catalog.regexp_replace(text,text,text) ya existe y gana la
resolucion.

T6 y T7 NO se pueden expresar con una expresion regular: los argumentos son
multilinea y llevan parentesis anidados, y el separador de LISTAGG es un
literal que puede contener cualquier cosa. Van con un emparejador que solo
cuenta los parentesis que estan en codigo.

DOS INVARIANTES, y la segunda es la que hace utilizable el reporte de errores:

  1. Nada dentro de un literal, un comentario o un identificador entre comillas
     dobles se toca jamas. Es la leccion que ya pago validar.sh: un ' -- '
     dentro de una cadena no es un comentario.
  2. Toda sustitucion CONSERVA EL NUMERO DE SALTOS DE LINEA. Lo que se acorta
     se rellena con '\n' al final. Asi la linea que reporta psql ES la linea
     del archivo original, y no hace falta mantener un mapa de lineas.
"""
import re
import sys

CODE, STR, CMT, IDENT = 1, 0, 0, 2


def mapa_codigo(s):
    """bytearray paralelo a s: 1 = codigo, 0 = literal/comentario, 2 = "ident".

    El cuerpo de un procedimiento va entre $$ y es CODIGO: hay que reescribir
    dentro. Los identificadores entre comillas dobles son los nombres que salen
    del relationalize ("location.val.contactinformations.val.contacttype") y
    tienen que quedar opacos: contienen puntos y podrian contener cualquier
    cosa, y ninguna regla debe morder ahi dentro.
    """
    m = bytearray([CODE]) * len(s)
    i, n = 0, len(s)
    while i < n:
        c = s[i]
        if c == '$':                                    # delimitador $tag$
            mm = re.match(r'\$[A-Za-z_0-9]*\$', s[i:])
            if mm:
                i += mm.end()                           # el interior es CODIGO
                continue
        if c == "'":                                    # literal de cadena
            j = i + 1
            while j < n:
                if s[j] == "'":
                    if j + 1 < n and s[j + 1] == "'":
                        j += 2
                        continue
                    j += 1
                    break
                j += 1
            for k in range(i, min(j, n)):
                m[k] = STR
            i = j
            continue
        if c == '"':                                     # identificador
            j = s.find('"', i + 1)
            j = n if j < 0 else j + 1
            for k in range(i, j):
                m[k] = IDENT
            i = j
            continue
        if c == '-' and i + 1 < n and s[i + 1] == '-':   # comentario de linea
            j = s.find('\n', i)
            j = n if j < 0 else j
            for k in range(i, j):
                m[k] = CMT
            i = j
            continue
        if c == '/' and i + 1 < n and s[i + 1] == '*':   # comentario de bloque
            j = s.find('*/', i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, min(j, n)):
                m[k] = CMT
            i = j
            continue
        i += 1
    return m


def es_cod(m, i):
    return m[i] == CODE


def cierra(s, m, abre):
    """Posicion del ')' que cierra el '(' de abre. Solo cuenta en codigo."""
    prof, i, n = 0, abre, len(s)
    while i < n:
        if es_cod(m, i):
            if s[i] == '(':
                prof += 1
            elif s[i] == ')':
                prof -= 1
                if prof == 0:
                    return i
        i += 1
    raise ValueError('parentesis sin cerrar en la posicion %d' % abre)


def parte_args(s, m, ini, fin):
    """Parte s[ini:fin] por las comas de nivel superior que esten en codigo."""
    args, prof, arr = [], 0, ini
    for i in range(ini, fin):
        if not es_cod(m, i):
            continue
        if s[i] == '(':
            prof += 1
        elif s[i] == ')':
            prof -= 1
        elif s[i] == ',' and prof == 0:
            args.append(s[arr:i])
            arr = i + 1
    args.append(s[arr:fin])
    return [a.strip() for a in args]


def busca_cod(s, m, patron, desde=0):
    """Primer match de patron cuyo inicio este en codigo."""
    rx = re.compile(patron, re.IGNORECASE)
    pos = desde
    while True:
        mm = rx.search(s, pos)
        if not mm:
            return None
        if es_cod(m, mm.start()):
            return mm
        pos = mm.start() + 1


def iguala_lineas(nuevo, viejo):
    """Invariante 2: el reemplazo conserva el numero de saltos de linea."""
    faltan = viejo.count('\n') - nuevo.count('\n')
    return nuevo + ('\n' * faltan if faltan > 0 else '')


class ErrorTranspila(Exception):
    pass


def _linea(s, pos):
    return s.count('\n', 0, pos) + 1


# --------------------------------------------------------------------------
def _reescribe_llamada(s, nombre, constructor, cuenta):
    """Recorre las llamadas a `nombre(...)` y las sustituye una a una.

    Rehace el mapa en cada vuelta porque el texto cambia de longitud. Es O(n^2)
    sobre archivos de 800 lineas: irrelevante, y a cambio es imposible
    desalinear indices.
    """
    pos = 0
    while True:
        m = mapa_codigo(s)
        mm = busca_cod(s, m, r'\b%s\s*\(' % nombre, pos)
        if not mm:
            return s
        ab = mm.end() - 1
        ci = cierra(s, m, ab)
        viejo, nuevo, fin = constructor(s, m, mm, ab, ci)
        cuenta[nombre] = cuenta.get(nombre, 0) + 1
        rep = iguala_lineas(nuevo, viejo)
        s = s[:mm.start()] + rep + s[fin:]
        # Avanzar PASADO el reemplazo, no un caracter. Varios reemplazos
        # contienen el mismo token que se busca -- GENERATED BY DEFAULT AS
        # IDENTITY(...) contiene IDENTITY(, rs.dateadd( contiene dateadd( --
        # y con pos+1 el transpilador se los volvia a comer en bucle.
        pos = mm.start() + len(rep)


def t6_listagg(s, cuenta):
    def c(s, m, mm, ab, ci):
        args = parte_args(s, m, ab + 1, ci)
        if len(args) != 2:
            raise ErrorTranspila(
                'linea %d: LISTAGG con %d argumentos; se esperaban 2'
                % (_linea(s, mm.start()), len(args)))
        if re.match(r'(?i)^DISTINCT\b', args[0]):
            # Cero sitios en los tres repos. Si aparece uno, hay que decidir
            # a mano: string_agg(DISTINCT x, s ORDER BY k) exige que el ORDER BY
            # sea por la misma expresion del DISTINCT, y Redshift no.
            raise ErrorTranspila(
                'linea %d: LISTAGG(DISTINCT ...) no se traduce a ciegas'
                % _linea(s, mm.start()))
        resto = s[ci + 1:]
        wg = re.match(r'(?is)\s*WITHIN\s+GROUP\s*\(', resto)
        if not wg:
            # Los 43 sitios de codigo llevan WITHIN GROUP. Sin el, el orden
            # queda indefinido y el banco no debe inventarlo.
            raise ErrorTranspila(
                'linea %d: LISTAGG sin WITHIN GROUP' % _linea(s, mm.start()))
        ab2 = ci + 1 + wg.end() - 1
        ci2 = cierra(s, mapa_codigo(s), ab2)
        orden = s[ab2 + 1:ci2].strip()
        nuevo = 'string_agg((%s)::text, %s %s)' % (args[0], args[1], orden)
        return s[mm.start():ci2 + 1], nuevo, ci2 + 1
    return _reescribe_llamada(s, 'LISTAGG', c, cuenta)


def t7_dateadd(s, cuenta):
    def c(s, m, mm, ab, ci):
        u, n, d = parte_args(s, m, ab + 1, ci)
        nuevo = "rs.dateadd('%s', (%s), (%s))" % (u.strip().strip("'").lower(), n, d)
        return s[mm.start():ci + 1], nuevo, ci + 1
    return _reescribe_llamada(s, 'DATEADD', c, cuenta)


def t7_datediff(s, cuenta):
    def c(s, m, mm, ab, ci):
        u, a, b = parte_args(s, m, ab + 1, ci)
        nuevo = "rs.datediff('%s', (%s), (%s))" % (u.strip().strip("'").lower(), a, b)
        return s[mm.start():ci + 1], nuevo, ci + 1
    return _reescribe_llamada(s, 'DATEDIFF', c, cuenta)


def t9_date_part(s, cuenta):
    """DATE_PART(year, x) -> DATE_PART('year', x).

    Redshift admite la unidad como palabra desnuda, igual que en DATEADD y
    DATEDIFF; Postgres la lee como una referencia a columna y falla con
    'column "year" does not exist'. El codigo del repo es correcto: el hueco era
    del transpilador. Si la unidad ya viene entre comillas no se toca.
    """
    def c(s, m, mm, ab, ci):
        args = parte_args(s, m, ab + 1, ci)
        if len(args) < 2 or not re.fullmatch(r'[A-Za-z_]+', args[0]):
            return s[mm.start():ci + 1], s[mm.start():ci + 1], ci + 1
        nuevo = "DATE_PART('%s', %s)" % (args[0].lower(), ', '.join(args[1:]))
        return s[mm.start():ci + 1], nuevo, ci + 1
    return _reescribe_llamada(s, 'DATE_PART', c, cuenta)


def t8_regexp_replace(s, cuenta):
    def c(s, m, mm, ab, ci):
        args = parte_args(s, m, ab + 1, ci)
        if len(args) != 3:                       # 4 argumentos ya trae bandera
            return s[mm.start():ci + 1], s[mm.start():ci + 1], ci + 1
        nuevo = "regexp_replace(%s, %s, %s, 'g')" % tuple(args)
        return s[mm.start():ci + 1], nuevo, ci + 1
    return _reescribe_llamada(s, 'REGEXP_REPLACE', c, cuenta)


def t3_llaves_con_parentesis(s, cuenta):
    def c(s, m, mm, ab, ci):
        return s[mm.start():ci + 1], ' ', ci + 1
    return _reescribe_llamada(
        s, r'(?:COMPOUND\s+|INTERLEAVED\s+)?(?:DISTKEY|SORTKEY)', c, cuenta)


def t5_identity(s, cuenta):
    def c(s, m, mm, ab, ci):
        args = parte_args(s, m, ab + 1, ci)
        sem, paso = (args + ['1', '1'])[:2]
        nuevo = ('GENERATED BY DEFAULT AS IDENTITY (START WITH %s INCREMENT BY %s)'
                 % (sem, paso))
        return s[mm.start():ci + 1], nuevo, ci + 1
    return _reescribe_llamada(s, 'IDENTITY', c, cuenta)


# Reglas sin parentesis. T4 va DESPUES de T3: lo que quede de DISTKEY/SORTKEY
# sin parentesis es la forma de nivel de columna.
SIMPLES = [
    ('T3-encode',    r'\bENCODE\s+\w+'),
    ('T3-diststyle', r'\bDISTSTYLE\s+(?:ALL|EVEN|AUTO|KEY)\b'),
    ('T3-backup',    r'\bBACKUP\s+NO\b'),
    ('T4-llave-col', r'\b(?:DISTKEY|SORTKEY)\b'),
    ('T1-nonatomic', r'\bNONATOMIC\b'),
    ('T2-binding',   r'\bWITH\s+NO\s+SCHEMA\s+BINDING\b'),
]


def simples(s, cuenta):
    for nombre, patron in SIMPLES:
        pos = 0
        while True:
            m = mapa_codigo(s)
            mm = busca_cod(s, m, patron, pos)
            if not mm:
                break
            cuenta[nombre] = cuenta.get(nombre, 0) + 1
            s = s[:mm.start()] + iguala_lineas(' ', mm.group(0)) + s[mm.end():]
            pos = mm.start() + 1
    return s


ORDEN = [t6_listagg, t7_dateadd, t7_datediff, t9_date_part, t8_regexp_replace,
         t5_identity, t3_llaves_con_parentesis, simples]


def transpila(s):
    """Devuelve (texto, conteo_por_regla)."""
    cuenta = {}
    for paso in ORDEN:
        s = paso(s, cuenta)
    return s, cuenta


def _leer(p):
    with open(p, encoding='utf-8', errors='surrogateescape', newline='') as f:
        return f.read()


def _escribir(p, s):
    with open(p, 'w', encoding='utf-8', errors='surrogateescape', newline='') as f:
        f.write(s)


if __name__ == '__main__':
    if len(sys.argv) == 3:
        orig = _leer(sys.argv[1])
        try:
            out, cnt = transpila(orig)
        except ErrorTranspila as e:
            sys.stderr.write('TRANSPILA %s: %s\n' % (sys.argv[1], e))
            sys.exit(2)
        if out.count('\n') != orig.count('\n'):
            sys.stderr.write('TRANSPILA %s: se movieron las lineas (%d -> %d)\n'
                             % (sys.argv[1], orig.count('\n'), out.count('\n')))
            sys.exit(3)
        _escribir(sys.argv[2], out)
        for k in sorted(cnt):
            sys.stderr.write('  %-14s %d\n' % (k, cnt[k]))
    else:
        sys.stdout.write(transpila(sys.stdin.read())[0])
